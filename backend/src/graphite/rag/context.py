"""Data structures and context models for Dual-Mode GraphRAG retrieval."""

from typing import Any, Dict, List, Optional, Tuple, Union
from pydantic import BaseModel, Field


class LocalRetrievalContext(BaseModel):
    """Component-level retrieval context containing K-hop subgraph, visual crops, and exact line paths."""
    target_node_id: str
    target_tag: Optional[str] = None
    target_label: str
    target_specs: Dict[str, Any] = Field(default_factory=dict)
    visual_crop_path: Optional[str] = None
    bounding_box: Optional[Tuple[float, float, float, float]] = None
    k_hop: int = 2
    subsystem_id: Optional[int] = None
    subsystem_name: Optional[str] = None
    subgraph_nodes: List[Dict[str, Any]] = Field(default_factory=list)
    subgraph_edges: List[Dict[str, Any]] = Field(default_factory=list)
    upstream_equipment: List[str] = Field(default_factory=list)
    downstream_equipment: List[str] = Field(default_factory=list)
    isolation_valves: List[str] = Field(default_factory=list)
    active_bypasses: List[List[str]] = Field(default_factory=list)

    def summary(self) -> str:
        """Formatted textual summary of local component neighborhood."""
        tag_str = f" [{self.target_tag}]" if self.target_tag else ""
        lines = [
            f"Component: {self.target_node_id}{tag_str} (Type: {self.target_label})",
            f"Subsystem: {self.subsystem_name or 'Unassigned'}",
            f"Technical Specs: {self.target_specs if self.target_specs else 'Standard rating'}",
            f"Visual Symbol Crop: {self.visual_crop_path or 'No crop available'}",
            f"{self.k_hop}-Hop Subgraph: {len(self.subgraph_nodes)} components, {len(self.subgraph_edges)} connecting pipe segments",
            f"Upstream Flow Origins: {', '.join(self.upstream_equipment) if self.upstream_equipment else 'None'}",
            f"Downstream Flow Destinations: {', '.join(self.downstream_equipment) if self.downstream_equipment else 'None'}",
            f"Required Boundary Isolation Valves: {', '.join(self.isolation_valves) if self.isolation_valves else 'None identified'}",
        ]
        return "\n".join(lines)


class GlobalRetrievalContext(BaseModel):
    """Plant-level retrieval context containing hierarchical subsystem summaries and domain groupings."""
    plant_name: str
    total_equipment_count: int
    total_pipe_segments: int
    total_subsystems: int
    domains: Dict[str, List[Dict[str, Any]]] = Field(default_factory=dict)
    critical_cut_valves: List[str] = Field(default_factory=list)
    subsystem_summaries: List[Dict[str, Any]] = Field(default_factory=list)

    def summary(self) -> str:
        """Formatted textual summary of plant-level hierarchical architecture."""
        lines = [
            f"Plant Hierarchy: {self.plant_name}",
            f"Total Physical Assets: {self.total_equipment_count} units across {self.total_pipe_segments} pipe lines",
            f"Total Subsystems: {self.total_subsystems}",
            "Domain Categorization:",
        ]
        for domain, subs in self.domains.items():
            lines.append(f"  * {domain} ({len(subs)} subsystems):")
            for s in subs:
                lines.append(
                    f"      - {s['name']}: {s['component_count']} components | "
                    f"Boundary Valves: {s.get('boundary_valves', [])}"
                )
        return "\n".join(lines)


class GraphRAGResponse(BaseModel):
    """Unified grounded response generated by the Dual-Mode GraphRAG Engine."""
    query: str
    retrieval_mode: str  # "local" or "global"
    grounded_answer: str
    context: Union[LocalRetrievalContext, GlobalRetrievalContext]
    visual_citations: List[str] = Field(default_factory=list)
    topological_citations: List[str] = Field(default_factory=list)
